#!/usr/bin/env python3
# Turn a PSF2 console font (optionally gzipped) into font.c for flboot:
# printable ASCII, looked up through the font's Unicode table.
#   mkfont.py FONT.psfu[.gz] > font.c
# SPDX-License-Identifier: MIT
import gzip, struct, sys

data = open(sys.argv[1], "rb").read()
if data[:2] == b"\x1f\x8b":
    data = gzip.decompress(data)
magic, version, hsize, flags, count, gsize, height, width = struct.unpack("<8I", data[:32])
if magic != 0x864AB572:
    sys.exit("not a PSF2 font")
glyphs = [data[hsize + i * gsize: hsize + (i + 1) * gsize] for i in range(count)]
cmap = {}
if flags & 1:  # Unicode table: UTF-8 sequences per glyph, 0xFF ends a glyph
    table = data[hsize + count * gsize:]
    glyph = 0
    for chunk in table.split(b"\xff")[:count]:
        for seq in chunk.split(b"\xfe")[0:1]:
            for ch in seq.decode("utf-8", "replace"):
                cmap.setdefault(ord(ch), glyph)
        glyph += 1
rowbytes = (width + 7) // 8
print("/* Generated by mkfont.py from %s -- do not edit. */" % sys.argv[1].rsplit("/", 1)[-1])
print("const int font_width = %d, font_height = %d, font_rowbytes = %d;" % (width, height, rowbytes))
print("const unsigned char font_glyphs[95][%d] = {" % gsize)
for c in range(32, 127):
    g = glyphs[cmap.get(c, c)]
    print("\t{" + ", ".join("0x%02x" % b for b in g) + "}, /* %r */" % chr(c))
print("};")
