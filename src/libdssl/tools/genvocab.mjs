// genvocab.mjs: write vocab.c / vocab.h from native/data/vocabulary.json of the DSSL repo.
//   node --permission --allow-fs-read=VOCAB.json --allow-fs-read=TOOLS --allow-fs-write=OUTDIR \
//        tools/genvocab.mjs VOCAB.json OUTDIR
// The word lists keep the engine's order (spec DIA-9: it decides did-you-mean ties). Each set
// also gets an index sorted by byte order, for binary search.
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const [vocabFile, outDir] = process.argv.slice(2);
const v = JSON.parse(readFileSync(vocabFile, 'utf8'));

// the resolver keeps this one private (resolver.js, HTML_ELEMENTS); copied from 0.16.3
const html = ('a,abbr,acronym,address,area,article,aside,audio,b,base,bdi,bdo,big,blockquote,body,br,button,canvas,caption,center,cite,code,col,colgroup,' +
  'data,datalist,dd,del,details,dfn,dialog,dir,div,dl,dt,em,embed,fieldset,figcaption,figure,font,footer,form,frame,frameset,h1,h2,h3,h4,h5,h6,head,header,hgroup,hr,html,' +
  'i,iframe,img,input,ins,kbd,label,legend,li,link,main,map,mark,marquee,menu,meta,meter,nav,nobr,noscript,object,ol,optgroup,option,output,p,param,picture,pre,progress,q,' +
  'rp,rt,ruby,s,samp,script,search,section,select,slot,small,source,span,strike,strong,style,sub,summary,sup,table,tbody,td,template,textarea,tfoot,th,thead,time,title,tr,' +
  'track,tt,u,ul,var,video,wbr,svg,math').split(',');

const sets = {
  STATE: v.stateWords,
  PSEUDO: v.pseudoElements,
  KEYWORD: v.cssKeywords,
  PROP: v.knownProps,
  UNITLESS_PROP: v.unitlessProps,
  TIME_PROP: v.timeProps,
  UNITLESS_FN: v.unitlessFns,
  LENGTH_FN: v.lengthFns,
  COLOR_WORD: v.colorWords,
  FLUID_PROP: v.fluidProps,
  SEMANTIC: v.semanticNames,
  NAMED_COLOR: Object.keys(v.namedColors),
  HTML: html,
};
const q = (s) => '"' + s.replace(/\\/g, '\\\\').replace(/"/g, '\\"') + '"';
let c = '/* generated by tools/genvocab.mjs from native/data/vocabulary.json of EHS-Studio/dssl ' + v.version + ' (MIT). Do not edit. */\n#include "vocab.h"\n\n';
let h = '/* generated by tools/genvocab.mjs. Do not edit. */\n#ifndef DSSL_VOCAB_H\n#define DSSL_VOCAB_H\n#include <stddef.h>\n\n' +
  'typedef struct { const char *const *words; const unsigned short *sorted; unsigned n; } VSet;\n' +
  'int vset_has(const VSet *s, const char *p, size_t n);\n\n';
for (const [name, list] of Object.entries(sets)) {
  const words = [...list];
  const idx = words.map((_, i) => i).sort((a, b) => (words[a] < words[b] ? -1 : words[a] > words[b] ? 1 : 0));
  c += `static const char *const w_${name}[] = {\n${words.map((w) => '\t' + q(w) + ',').join('\n')}\n};\n`;
  c += `static const unsigned short i_${name}[] = {${idx.join(',')}};\n`;
  c += `const VSet V_${name} = { w_${name}, i_${name}, ${words.length} };\n\n`;
  h += `extern const VSet V_${name};\n`;
}
// default tokens, in map order
const dt = Object.entries(v.defaultTokens);
c += `const struct vtok V_DEFAULT_TOKENS[] = {\n${dt.map(([k, x]) => `\t{ ${q(k)}, ${q(x)} },`).join('\n')}\n};\nconst unsigned V_DEFAULT_TOKENS_N = ${dt.length};\n`;
h += '\nstruct vtok { const char *key, *value; };\nextern const struct vtok V_DEFAULT_TOKENS[];\nextern const unsigned V_DEFAULT_TOKENS_N;\n';
h += '\n#endif\n';
c += `
int vset_has(const VSet *s, const char *p, size_t n)
{
	unsigned lo = 0, hi = s->n;
	while (lo < hi) {
		unsigned mid = (lo + hi) / 2;
		const char *w = s->words[s->sorted[mid]];
		size_t wl = 0;
		while (w[wl]) wl++;
		size_t m = wl < n ? wl : n;
		int r = 0;
		for (size_t i = 0; i < m && !r; i++) r = (unsigned char)w[i] - (unsigned char)p[i];
		if (!r) r = wl < n ? -1 : wl > n ? 1 : 0;
		if (r == 0) return 1;
		if (r < 0) lo = mid + 1; else hi = mid;
	}
	return 0;
}
`;
writeFileSync(join(outDir, 'vocab.c'), c);
writeFileSync(join(outDir, 'vocab.h'), h);
console.log(Object.entries(sets).map(([k, l]) => k + ' ' + l.length).join(', '));
