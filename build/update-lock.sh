#!/bin/bash
# Regenerate sources.lock from sources.list: download every source into the
# cache, optionally cross-check it against upstream checksum lists, and record
# its SHA256.
#
# usage: update-lock.sh [-m md5sums-file]... [-s sha256sums-file]...
#   -m / -s  reference checksum lists ("<hash>  <filename>" lines, e.g. the
#            LFS md5sums or kernel.org sha256sums.asc). A file listed there
#            must match, or the lock is not written.

set -euo pipefail
. "$(dirname "$0")/config.sh"
. "$(dirname "$0")/lib.sh"

md5refs=() sha256refs=()
while getopts m:s: opt; do
	case $opt in
	m) md5refs+=("$OPTARG") ;;
	s) sha256refs+=("$OPTARG") ;;
	*) die "usage: $0 [-m md5sums]... [-s sha256sums]..." ;;
	esac
done

# ref_hash FILENAME REFFILE... -- print the hash a reference list gives FILENAME
ref_hash() {
	local name=$1; shift
	[ $# -gt 0 ] || return 0
	awk -v n="$name" '$2 == n { print $1; exit }' "$@"
}

mkdir -p "$FLFS_CACHE"
# Written next to the real lock and renamed over it, so a build reading
# sources.lock never sees a half-written file.
lock=$(mktemp "$FLFS_TOP/.sources.lock.XXXXXX")
trap 'rm -f "$lock"' EXIT

{
	echo "# FreeLFS source lock. Generated by build/update-lock.sh -- do not edit."
	echo "# sha256  file  url"
} > "$lock"

count=0 checked=0
while read -r url; do
	file=${url##*/}
	dest=$FLFS_CACHE/$file
	if [ ! -f "$dest" ]; then
		msg "downloading $file"
		download "$url" "$dest" || die "download failed: $url"
	fi

	sha=$(sha256sum "$dest" | cut -d' ' -f1)

	want=$(ref_hash "$file" "${md5refs[@]+"${md5refs[@]}"}")
	if [ -n "$want" ]; then
		[ "$(md5sum "$dest" | cut -d' ' -f1)" = "$want" ] ||
			die "$file: md5 does not match reference list"
		checked=$((checked + 1))
	fi
	want=$(ref_hash "$file" "${sha256refs[@]+"${sha256refs[@]}"}")
	if [ -n "$want" ]; then
		[ "$sha" = "$want" ] || die "$file: sha256 does not match reference list"
		checked=$((checked + 1))
	fi

	printf '%s  %s  %s\n' "$sha" "$file" "$url" >> "$lock"
	count=$((count + 1))
done < <(grep -Ev '^\s*(#|$)' "$FLFS_TOP/sources.list")

chmod 644 "$lock"
mv "$lock" "$FLFS_TOP/sources.lock"
msg "sources.lock: $count sources ($checked cross-checked against reference lists)"
