#!/bin/bash
# Round 22: stage the signed flpkg repo for publishing on GitHub Releases, and print the upload plan.
# Nothing is uploaded: this script only reads the repo (build/70-repo.sh made it) and writes into
# $FLFS_WORK/publish/. The person who owns the GitHub login runs the printed commands (or the generated
# publish/upload.sh) later.
#
#   build/70-publish-repo.sh [--tag TAG] [--github OWNER/REPO]
#
# Hosting: one GitHub release per architecture, tag repo-ARCH (default repo-x86_64), with every repo
# file as a release asset: index.zst, index.zst.sig, NAME-VERSION-RELEASE-ARCH.flpkg and its .sig.
# The clients' repo URL is   https://github.com/OWNER/REPO/releases/download/TAG   (config/flpkg/repo-url,
# written by 70-repo.sh from FLFS_REPO_URL); flpkg fetches URL/index.zst and URL/NAME.flpkg with curl -L.
# Why Releases and not Pages: assets are up to 2 GiB each (a kernel or the firmware package is hundreds of
# MB) and are not part of the git history, so the repo stays small. Limits checked here: under 1000 assets,
# each under 2 GiB. The signatures, not the host, are what clients trust (signed index with serial and
# valid-until, signed packages), so a compromised release page cannot push unsigned or old files.
#
# What is staged (hard links, no copy): the files of the repo, plus the PUBLIC key as freelfs-repo.pub.
# What is never staged: any *.key. The script refuses to continue if a secret key or a file that looks
# like one is anywhere in the staging directory, and checks the repo directory and the git tree too.
set -euo pipefail
. "$(dirname "$0")/config.sh"
. "$(dirname "$0")/lib.sh"
[ "$EUID" -ne 0 ] || die "do not run this as root"

TAG=repo-$FLFS_ARCH
GH=wasselnl77-hash/freelfs
while [ $# -gt 0 ]; do
	case $1 in
		--tag) TAG=$2; shift 2 ;;
		--github) GH=$2; shift 2 ;;
		*) die "usage: $0 [--tag TAG] [--github OWNER/REPO]" ;;
	esac
done
REPO=${FLFS_REPO_DIR:-$FLFS_WORK/repo/$FLFS_ARCH}
PUB=${FLFS_PUBLISH_DIR:-$FLFS_WORK/publish}
STAGE=$PUB/$TAG
URL=https://github.com/$GH/releases/download/$TAG
[ -s "$REPO/index.zst" ] && [ -s "$REPO/index.zst.sig" ] || die "no signed index in $REPO (run build/70-repo.sh first)"

# the secret key must be nowhere it could be uploaded
if find "$REPO" -name '*.key' -o -name '*.sec' | grep -q .; then die "a secret key is inside the repo directory $REPO"; fi
if git -C "$FLFS_TOP" ls-files | grep -E '\.key$|repo-key' | grep -q .; then die "a key file is tracked in git"; fi
git -C "$FLFS_TOP" check-ignore -q repo-key/x.key || die ".gitignore does not cover *.key"

rm -rf "$STAGE"
mkdir -p "$STAGE"
shopt -s nullglob
n=0
for f in "$REPO"/*; do
	b=$(basename "$f")
	case $b in
		*.key | *.sec | *.part | *.tmp) die "refusing to stage $b" ;;
		index.zst | index.zst.sig | *.flpkg | *.flpkg.sig | *.pub | *.pub.sig) ;;
		*) warn "skipping $b (not a repo file)"; continue ;;
	esac
	ln "$f" "$STAGE/$b" 2> /dev/null || cp "$f" "$STAGE/$b"
	n=$((n + 1))
done
[ "$n" -lt 1000 ] || die "$n assets: a GitHub release holds at most 1000; split the repo (e.g. a second tag)"
big=$(find "$STAGE" -type f -size +2000M | head -n 1)
[ -z "$big" ] || die "$big is over 2 GiB, the limit of a release asset"
KEYFILE=${FLFS_REPO_KEY:-$FLFS_WORK/repo-key/freelfs}.key
if [ -f "$KEYFILE" ]; then
	ksum=$(sha256sum < "$KEYFILE" | cut -d' ' -f1)
	if (cd "$STAGE" && sha256sum -- *) | grep -q "^$ksum "; then die "the private key is among the staged files"; fi
fi
(cd "$STAGE" && sha256sum -- * > "$PUB/$TAG.sha256.new")

# what changed since the last staging: new or different files; the index goes last
old=$PUB/$TAG.sha256
: > "$PUB/$TAG.upload"
while read -r sum name; do
	grep -qx "$sum  $name" "$old" 2> /dev/null && continue
	case $name in index.zst | index.zst.sig) ;; *) echo "$name" >> "$PUB/$TAG.upload" ;; esac
done < "$PUB/$TAG.sha256.new"
printf '%s\n' index.zst index.zst.sig >> "$PUB/$TAG.upload"
: > "$PUB/$TAG.delete"
if [ -f "$old" ]; then
	while read -r _ name; do grep -q "  $name\$" "$PUB/$TAG.sha256.new" || echo "$name" >> "$PUB/$TAG.delete"; done < "$old"
fi
mv "$PUB/$TAG.sha256.new" "$PUB/$TAG.sha256.staged"

cat > "$PUB/upload.sh" <<UP
#!/bin/bash
# Generated by build/70-publish-repo.sh. Uploads the staged repo to GitHub Releases. NOT run by the build.
# Needs: gh logged in as the owner of $GH (gh auth status). Run from anywhere.
set -euo pipefail
cd "$STAGE"
gh release view $TAG --repo $GH > /dev/null 2>&1 || \\
	gh release create $TAG --repo $GH --title "FreeLFS package repository ($FLFS_ARCH)" \\
		--notes "Signed flpkg repository. Clients use https://github.com/$GH/releases/download/$TAG as the repo URL (set in /etc/flpkg.conf). Files are replaced in place; do not download by hand." --latest=false
# packages first, the signed index last: a client never sees an index that points at missing files
UP
{
	echo "gh release upload $TAG --repo $GH --clobber \\"
	grep -vx 'index.zst\|index.zst.sig' "$PUB/$TAG.upload" | awk '!s[$0]++ { a[++n] = $0 } END { for (i = 1; i <= n; i++) printf "\t\"%s\"%s\n", a[i], (i < n ? " \\" : "") }'
	echo "gh release upload $TAG --repo $GH --clobber index.zst index.zst.sig"
	while read -r dn; do [ -n "$dn" ] && echo "gh release delete-asset $TAG \"$dn\" --repo $GH --yes"; done < "$PUB/$TAG.delete"
	echo "# check the result the way a client does (sync from the URL needs the key from the image):"
	echo "curl -fsSL -o /dev/null -w '%{http_code}\n' $URL/index.zst"
	echo "echo 'now run: mv $PUB/$TAG.sha256.staged $PUB/$TAG.sha256   (so the next staging only uploads what changed)'"
} >> "$PUB/upload.sh"
chmod +x "$PUB/upload.sh"
# tidy: with no package file changed the "gh release upload" line has only the pub key
size=$(du -shL "$STAGE" | cut -f1)
msg "staged $n files ($size) in $STAGE"
cat <<TXT

UPLOAD PLAN  (nothing has been uploaded)
  release   $TAG on https://github.com/$GH
  client URL  $URL      (config/flpkg/repo-url must say this; image repo line: "repo freelfs $URL")
  to upload   $(($(wc -l < "$PUB/$TAG.upload") + 1)) files: $(grep -vx 'index.zst\|index.zst.sig' "$PUB/$TAG.upload" | wc -l) changed package files, then index.zst and index.zst.sig last, plus freelfs-repo.pub
  to delete   $(wc -l < "$PUB/$TAG.delete") stale assets (removed or replaced versions)
  commands    $PUB/upload.sh      (read it, then run it as the GitHub account owner)
  the key     the PRIVATE signing key is $FLFS_WORK/repo-key/freelfs.key: not in git, not in the image, not staged
  validity    the signed index expires: re-run build/70-repo.sh and this script, then upload.sh, before then
TXT
